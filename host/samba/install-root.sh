#!/bin/bash
# Install the sheeta LAN Samba server.
#
# Run as root in a root SSH session (sudo is not installed on this box).
# Review /data/stacks/host/samba/README.md before you run this.
#
# The script installs the samba package, copies this tree into /etc/samba,
# enables NetBIOS name sheeta, and starts smbd and nmbd.
# Re-run it after you change a share link.

SRC="/data/stacks/host/samba"
SHARE_PATH="/data/volumes/sabnzbd/config/Downloads/complete"

echo "install-root: start"

if [ "$(id -u)" -ne 0 ]
then
    echo "install-root: ERROR must run as root"
    exit 1
fi

if [ ! -d "${SHARE_PATH}" ]
then
    echo "install-root: ERROR missing ${SHARE_PATH}"
    exit 1
fi

ENABLED_COUNT="$(find "${SRC}/shares-enabled" -maxdepth 1 -type l -name '*.conf' | wc -l)"
if [ "${ENABLED_COUNT}" -gt 1 ]
then
    echo "install-root: ERROR more than one share is enabled"
    echo "install-root: run enable-share.sh with the one share you want"
    exit 1
fi

echo "install-root: apt-get update"
apt-get update
if [ $? -ne 0 ]
then
    echo "install-root: ERROR apt-get update failed"
    exit 1
fi

echo "install-root: apt-get install samba"
DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends samba
if [ $? -ne 0 ]
then
    echo "install-root: ERROR apt-get install samba failed"
    exit 1
fi

if [ -f /usr/lib/systemd/system/samba-ad-dc.service ] || [ -f /lib/systemd/system/samba-ad-dc.service ]
then
    echo "install-root: disable samba-ad-dc"
    systemctl disable --now samba-ad-dc.service
    if [ $? -ne 0 ]
    then
        echo "install-root: ERROR disable samba-ad-dc failed"
        exit 1
    fi
fi

if [ -f /etc/samba/smb.conf ] && [ ! -f /etc/samba/smb.conf.debian-original ]
then
    if ! grep -q 'sheeta-lan-share' /etc/samba/smb.conf
    then
        echo "install-root: keep Debian smb.conf as smb.conf.debian-original"
        cp -a /etc/samba/smb.conf /etc/samba/smb.conf.debian-original
        if [ $? -ne 0 ]
        then
            echo "install-root: ERROR backup smb.conf failed"
            exit 1
        fi
    fi
fi

echo "install-root: copy smb.conf"
cp -a "${SRC}/smb.conf" /etc/samba/smb.conf
if [ $? -ne 0 ]
then
    echo "install-root: ERROR copy smb.conf failed"
    exit 1
fi

echo "install-root: copy shares"
rm -rf /etc/samba/shares-available /etc/samba/shares-enabled
mkdir -p /etc/samba/shares-available /etc/samba/shares-enabled
if [ $? -ne 0 ]
then
    echo "install-root: ERROR mkdir shares failed"
    exit 1
fi

cp -a "${SRC}/shares-available/." /etc/samba/shares-available/
if [ $? -ne 0 ]
then
    echo "install-root: ERROR copy shares-available failed"
    exit 1
fi

for LINK in "${SRC}/shares-enabled"/*.conf
do
    if [ ! -L "${LINK}" ]
    then
        continue
    fi
    BASE="$(basename "${LINK}")"
    TARGET="$(basename "$(readlink "${LINK}")")"
    ln -s "../shares-available/${TARGET}" "/etc/samba/shares-enabled/${BASE}"
    if [ $? -ne 0 ]
    then
        echo "install-root: ERROR link ${BASE} failed"
        exit 1
    fi
done

echo "install-root: write includes.conf"
INCLUDE_TMP="/etc/samba/includes.conf.tmp"
echo "# Generated by install-root.sh. Re-run that script to change shares." > "${INCLUDE_TMP}"
FOUND=0
for SHARE in /etc/samba/shares-enabled/*.conf
do
    if [ ! -e "${SHARE}" ] && [ ! -L "${SHARE}" ]
    then
        continue
    fi
    echo "include = ${SHARE}" >> "${INCLUDE_TMP}"
    FOUND=1
done
if [ "${FOUND}" -eq 0 ]
then
    echo "# No share is enabled." >> "${INCLUDE_TMP}"
fi
mv "${INCLUDE_TMP}" /etc/samba/includes.conf
if [ $? -ne 0 ]
then
    echo "install-root: ERROR write includes.conf failed"
    exit 1
fi

echo "install-root: testparm"
testparm -s /etc/samba/smb.conf
if [ $? -ne 0 ]
then
    echo "install-root: ERROR testparm failed"
    exit 1
fi

echo "install-root: install NetBIOS rebind hook"
cp -a "${SRC}/dhclient-samba-netbios" /etc/dhcp/dhclient-exit-hooks.d/samba-netbios
if [ $? -ne 0 ]
then
    echo "install-root: ERROR copy dhcp hook failed"
    exit 1
fi
chmod 755 /etc/dhcp/dhclient-exit-hooks.d/samba-netbios
if [ $? -ne 0 ]
then
    echo "install-root: ERROR chmod dhcp hook failed"
    exit 1
fi

echo "install-root: install enp2s0 dhcp"
cp -a "${SRC}/iface-enp2s0" /etc/network/interfaces.d/enp2s0
if [ $? -ne 0 ]
then
    echo "install-root: ERROR copy enp2s0 iface failed"
    exit 1
fi

echo "install-root: enable smbd and nmbd"
systemctl enable smbd.service nmbd.service
if [ $? -ne 0 ]
then
    echo "install-root: ERROR enable samba failed"
    exit 1
fi

echo "install-root: start smbd and nmbd"
systemctl restart smbd.service nmbd.service
if [ $? -ne 0 ]
then
    echo "install-root: ERROR start samba failed"
    exit 1
fi

echo "install-root: done"
echo "install-root: NetBIOS name is sheeta"
echo "install-root: share is //sheeta/sabnzbd"
echo "install-root: check with: nmblookup sheeta"
echo "install-root: check with: smbclient -L 127.0.0.1 -N"
exit 0
